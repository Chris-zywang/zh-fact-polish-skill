"""硬性语病规则（高精度、低召回）：“了”的位置、的/得混用、标点重复等。
每条规则只在小句（逗号/分号切分）内匹配，避免跨小句误报。"""
import re

# 含“了”但与体貌助词无关的词，匹配前先遮蔽
LE_WORDS = re.compile(r'为了|除了|了解|了不起|了无|了却|了结|了然|(?:草草|敷衍)了事|了得(?![一-鿿])|'
                      r'罢了|极了|不了|得了|受不了|免不了|少不了|忘不了|算了|末了|终了|未了')
MASK = '□'

LE_RULES = [
    # 否定 + 动词 + 了 + 宾语：“没有完成了任务”
    (r'(?:没有|没|未曾|未)(?!因此|因为|让|使|把|被|对)[一-鿿]{1,3}了(?=[一-鿿])(?![^，。]*(?:之前|以前|为止))',
     '否定句中误用“了”', '“没（有）”与完成体“了”冲突，删去“了”，如“没有完成了任务”→“没有完成任务”'),
    # 将来时标记 + 动词 + 了 + 宾语：“必将改变了世界”
    (r'(?:将会|必将|终将|将要|即将|就要)[一-鿿]{1,3}了(?=[一-鿿])',
     '将来时误用“了”', '表示将来的句子不用完成体“了”，删去“了”'),
    # 进行体 + 了：“正在进行了讨论”
    (r'正在[一-鿿]{1,4}了(?![解不])',
     '进行体误用“了”', '“正在”表示进行，不能与“了”连用，删去“了”或改为“着”'),
    # 了 + 结果补语：“看了完”“听了懂”
    (r'(?<![过])[看听读写做吃说学]了(?:完|掉|懂|清楚|明白)(?![全成美整毕善事])',
     '“了”位置错误', '“了”应放在补语之后，如“看了完”→“看完了”'),
    # 了的：“完成了的任务”
    # 只抓“已/已经…了的”这类明确冗余；“翻了的盆”“放久了的猪肝”是正常口语，不报
    (r'已(?:经)?[一-鿿]{1,3}了的(?=[一-鿿])',
     '“已…了的”冗余', '“已经”与“了”重复表示完成，删去“了”，如“已经完成了的任务”→“已经完成的任务”'),
    # 重复“了了”
    (r'了了', '“了”重复', '删去多余的“了”'),
]

OTHER_RULES = [
    # 只在常见单音节动词/形容词后检查，避免“目的十分明确”这类误报
    (r'(?<![目])[跑走说写做学长变活睡吃笑哭唱跳干看听讲想打读算答]的(?:很|非常|十分|特别|格外|相当|太)(?![多少规])',
     '“的/得”混用', '动词后接程度补语用“得”，如“跑的很快”→“跑得很快”'),
    (r'([，。！？；：、])\1', '标点重复', '删去重复的标点'),
    (r'[，、；：][。！？]|[。！？][，、；]', '标点连用错误', '保留一个合适的标点'),
    (r'(?<=[一-鿿])[,;](?=[一-鿿])', '中文中混用半角标点', '改为全角“，”“；”'),
]


def check_clause(clause):
    """返回 [(rule, 建议, 命中片段, 起止)]"""
    masked = LE_WORDS.sub(lambda m: MASK * len(m.group(0)), clause)
    hits = []
    for pat, name, sug in LE_RULES:
        for m in re.finditer(pat, masked):
            hits.append((name, sug, clause[m.start():m.end()], m.start()))
    for pat, name, sug in OTHER_RULES:
        for m in re.finditer(pat, clause):
            hits.append((name, sug, clause[m.start():m.end()], m.start()))
    return hits
